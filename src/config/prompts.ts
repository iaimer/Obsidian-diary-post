export function normalizePolishPrompt(prompt: unknown): string {
  if (typeof prompt !== 'string' || !prompt.trim()) return DEFAULT_POLISH_PROMPT;
  if (prompt.includes('【标签规则】') || prompt.includes('【固定标签规则】')) {
    return DEFAULT_POLISH_PROMPT;
  }
  return prompt;
}
